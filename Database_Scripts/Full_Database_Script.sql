    RETURN QUERY
    SELECT 
        v_total,
        c."ArticleCategoryId",
        c."Name",
        c."Slug",
        c."Description",
        c."SortOrder",
        c."CreatedAt",
        c."UpdatedAt"
    FROM "Tbl_ArticleCategory" c
    WHERE c."IsDeleted" = FALSE
      AND (p_search_keyword IS NULL OR c."Name" ILIKE '%' || p_search_keyword || '%')
    ORDER BY c."SortOrder" ASC, c."CreatedAt" ASC
    OFFSET (p_page - 1) * p_page_size
    LIMIT p_page_size;
END;
$$ LANGUAGE plpgsql;

