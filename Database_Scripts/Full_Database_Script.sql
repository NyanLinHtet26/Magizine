CREATE OR REPLACE FUNCTION fn_get_article_category_list(
    p_search_keyword TEXT DEFAULT NULL,
    p_is_active BOOLEAN DEFAULT NULL, -- Ignored safely; category table uses soft-delete
    p_page INT DEFAULT 1,
    p_page_size INT DEFAULT 20
)
RETURNS TABLE (
    "TotalCount" BIGINT,
    "ArticleCategoryId" BIGINT,
    "Name" VARCHAR,
    "Slug" VARCHAR,
    "Description" VARCHAR,
    "SortOrder" INT,
    "CreatedAt" TIMESTAMPTZ,
    "UpdatedAt" TIMESTAMPTZ
) AS $$
DECLARE
    v_total BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_total
    FROM "Tbl_ArticleCategory" c
    WHERE c."IsDeleted" = FALSE
